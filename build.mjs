// Bundles src/index.ts into dist/index.js and writes dist/THIRD_PARTY_LICENSES.txt
// from the packages esbuild actually bundled. `node build.mjs --watch` rebuilds both.
import * as esbuild from "esbuild";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.dirname(fileURLToPath(import.meta.url));
const LICENSES = path.join(root, "dist", "THIRD_PARTY_LICENSES.txt");
const RULE = "=".repeat(80);

const INTRO = `Third-party software bundled in dist/index.js

dist/index.js is built with esbuild and includes the packages below, each under
its own license. Everything else in it is acro-td-mcp's own code, under the MIT
license in ../LICENSE.

Generated by build.mjs. Don't edit by hand.
`;

// Package folders (node_modules/<name> or node_modules/@scope/<name>) of every bundled input
function packageDirs(metafile) {
  const dirs = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const parts = input.split("/");
    const i = parts.lastIndexOf("node_modules");
    if (i < 0) continue;
    const length = parts[i + 1].startsWith("@") ? 2 : 1;
    dirs.add(parts.slice(0, i + 1 + length).join("/"));
  }
  return [...dirs];
}

function licenseId(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type).join(" OR ");
  return "UNKNOWN";
}

function entry(dir) {
  const abs = path.join(root, dir);
  const pkg = JSON.parse(fs.readFileSync(path.join(abs, "package.json"), "utf8"));
  const file = fs.readdirSync(abs).sort().find((f) => /^(licen[cs]e|copying)/i.test(f));
  let body;
  if (file) {
    body = fs.readFileSync(path.join(abs, file), "utf8").replace(/\r\n?/g, "\n").trim();
  } else {
    // Name only: drop the "<email>" and "(url)" parts of an author string
    const author = (typeof pkg.author === "string" ? pkg.author : pkg.author?.name)
      ?.replace(/\s*[<(].*?[>)]/g, "").trim();
    const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
    body = [
      `${licenseId(pkg)} license. The package ships no license file.`,
      author && `Author: ${author}`,
      repo && `Repository: ${repo}`,
    ].filter(Boolean).join("\n");
  }
  return {
    id: `${pkg.name}@${pkg.version}`,
    name: pkg.name,
    version: pkg.version,
    text: `${RULE}\n${pkg.name}@${pkg.version} (${licenseId(pkg)})\n${RULE}\n\n${body}\n`,
  };
}

function writeLicenses(metafile) {
  const entries = new Map();
  for (const dir of packageDirs(metafile)) {
    const e = entry(dir);
    entries.set(e.id, e);
  }
  const sorted = [...entries.values()]
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : a.version < b.version ? -1 : 1))
    .map((e) => e.text);
  fs.writeFileSync(LICENSES, [INTRO, ...sorted].join("\n"));
}

const options = {
  absWorkingDir: root,
  entryPoints: ["src/index.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: "dist/index.js",
  banner: { js: "import { createRequire } from 'module'; const require = createRequire(import.meta.url);" },
  metafile: true,
  logLevel: "info",
  plugins: [{
    name: "third-party-licenses",
    setup(build) {
      build.onEnd((result) => {
        if (result.metafile) writeLicenses(result.metafile);
      });
    },
  }],
};

if (process.argv.includes("--watch")) {
  await (await esbuild.context(options)).watch();
} else {
  await esbuild.build(options);
}
